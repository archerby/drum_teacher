/*
 * Блокфлейта сопрано (строй «до»): аппликатура и уроки.
 * Аппликатура: «большой палец + 7 отверстий» сверху вниз.
 *   1 — закрыто, 0 — открыто, h — наполовину (большой палец приоткрыт / одно из двойных отверстий).
 * Отверстия 1–3 — левая рука, 4–7 — правая; 6 и 7 обычно двойные.
 * Ноты — в тех же обозначениях, что у металлофона: c1 — самая низкая нота (все отверстия закрыты).
 */
window.FINGERINGS = (() => {
  const baroque = {
    'c1': '1 1111111', 'c#1': '1 111111h', 'd1': '1 1111110', 'd#1': '1 11111h0',
    'e1': '1 1111100', 'f1': '1 1111011', 'f#1': '1 1110110', 'g1': '1 1110000',
    'g#1': '1 11011h0', 'a1': '1 1100000', 'a#1': '1 1011000', 'b1': '1 1000000',
    'c2': '1 0100000', 'c#2': '0 1100000', 'd2': '0 0100000', 'd#2': '0 0111110',
    'e2': 'h 1111100', 'f2': 'h 1111010', 'f#2': 'h 1110100', 'g2': 'h 1110000',
    'g#2': 'h 1101000', 'a2': 'h 1100000', 'a#2': 'h 1101110', 'b2': 'h 1101100',
    'c3': 'h 1001100',
  };
  // Немецкая система отличается в основном нотами фа
  const german = { ...baroque, 'f1': '1 1111000', 'f#1': '1 1110111', 'f2': 'h 1111000' };
  const parse = (s) => {
    const [t, h] = s.split(' ');
    return { thumb: t, holes: h.split('') };
  };
  const out = { baroque: {}, german: {} };
  Object.keys(baroque).forEach((k) => {
    out.baroque[k] = parse(baroque[k]);
    out.german[k] = parse(german[k]);
  });
  return out;
})();

