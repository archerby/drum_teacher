/* Нормализация: убрать пробелы/черты, проверить длину. */
(function normalize() {
  const clean = (s) => (s || '').replace(/[\s|]/g, '');
  RHYTHMS.forEach((r) => {
    r.bars = r.bars || 1;
    const total = r.beats * r.spb * r.bars;
    r.tracks.forEach((t) => {
      t.p = clean(t.p);
      if (t.p.length !== total) {
        console.warn('Ритм', r.id, t.i, 'длина', t.p.length, '≠', total);
        t.p = t.p.padEnd(total, '.').slice(0, total);
      }
    });
    if (r.hands) {
      r.hands = clean(r.hands);
      if (r.hands.length !== total) console.warn('Ритм', r.id, 'руки: длина', r.hands.length, '≠', total);
      r.hands = r.hands.padEnd(total, '.').slice(0, total);
    }
  });
})();
